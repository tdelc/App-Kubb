  dbx_get(con, "
    SELECT m.*, th.nom AS home, ta.nom AS away
    FROM matches m
    JOIN teams th ON th.team_id = m.home_id
    JOIN teams ta ON ta.team_id = m.away_id
    ORDER BY m.journee, m.date_match, m.match_id")
