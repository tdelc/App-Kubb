# ------------------------------------------------------------------
# Écriture : toute variation de StatCoins passe par le grand livre
# ------------------------------------------------------------------

add_transaction <- function(con, user_id, montant, motif) {
  dbx_exec(con, "
    INSERT INTO transactions (user_id, montant, motif) VALUES (?, ?, ?)",
           params = list(user_id, montant, motif))
  dbx_exec(con, "
    UPDATE users SET statcoins = statcoins + ? WHERE user_id = ?",
           params = list(montant, user_id))
}

# Placement atomique d'un pari sur le champion : débit du solde, insertion
# du pari, écriture au grand livre et bascule de version en une transaction
# (CTE). Le garde-fou statcoins >= mise interdit tout solde négatif, même en
# all-in. Renvoie le bet_id créé, ou un data.frame vide si solde insuffisant.
place_champion_bet <- function(con, user_id, team_id, score, mise, cote) {
  dbx_get(con, "
    WITH u AS (
      UPDATE users SET statcoins = statcoins - ?::double precision
      WHERE user_id = ?::int AND statcoins >= ?::double precision
      RETURNING user_id
    ), b AS (
      INSERT INTO champion_bets (user_id, team_id, score, mise, cote)
      SELECT user_id, ?::int, ?::text, ?::double precision, ?::double precision
      FROM u
      RETURNING bet_id
    ), t AS (
      INSERT INTO transactions (user_id, montant, motif)
      SELECT user_id, ?::double precision, ?::text FROM u
    ), v AS (
      UPDATE meta SET version = version + 1 WHERE EXISTS (SELECT 1 FROM u)
    )
    SELECT bet_id FROM b",
    params = list(mise, user_id, mise,
                  team_id, score, mise, unname(cote),
                  -mise, "Mise sur le champion du tournoi"))
}

# ------------------------------------------------------------------
# Annulation de paris (admin) : rembourse la mise, trace dans le grand
# livre, supprime le pari. Atomique par pari (CTE), et restreint aux
# paris NON réglés (settled = 0) : on ne touche jamais à un match déjà
# joué. Les bet_id déjà réglés ou inexistants sont silencieusement
# ignorés (le garde-fou SQL empêche tout double remboursement, même si
# la sélection de l'admin était périmée).
# ------------------------------------------------------------------

annuler_paris <- function(con, bet_ids) {
  bet_ids <- unique(as.integer(bet_ids))
  bet_ids <- bet_ids[!is.na(bet_ids)]
  
  n_ok <- 0L
  total_rendu <- 0
  
  for (bid in bet_ids) {
    res <- dbx_get(con, "
      WITH d AS (
        DELETE FROM bets
        WHERE bet_id = ? AND settled = 0
        RETURNING bet_id, user_id, mise
      ), u AS (
        UPDATE users SET statcoins = statcoins + (SELECT mise FROM d)
        WHERE user_id = (SELECT user_id FROM d)
        RETURNING user_id
      ), t AS (
        INSERT INTO transactions (user_id, montant, motif)
        SELECT user_id, mise,
               '[Admin] Annulation du pari #' || bet_id::text
        FROM d
      )
      SELECT mise FROM d",
                   params = list(bid))
    
    if (nrow(res) == 1) {
      n_ok <- n_ok + 1L
      total_rendu <- total_rendu + res$mise[1]
    }
  }
  
  # Une seule bascule de version : réveille les sessions (solde + tables)
  if (n_ok > 0) db_touch(con)

  list(n_annules = n_ok,
       total_rendu = total_rendu,
       n_ignores = length(bet_ids) - n_ok)
}

# ------------------------------------------------------------------
# Annulation de paris sur le champion (admin) : même principe que
# annuler_paris(), mais sur la table champion_bets. Restreint aux paris
# non réglés (settled = 0) : une fois le champion désigné, plus rien à
# annuler. Atomique par pari, remboursement tracé au grand livre.
# ------------------------------------------------------------------

annuler_paris_champion <- function(con, bet_ids) {
  bet_ids <- unique(as.integer(bet_ids))
  bet_ids <- bet_ids[!is.na(bet_ids)]

  n_ok <- 0L
  total_rendu <- 0

  for (bid in bet_ids) {
    res <- dbx_get(con, "
      WITH d AS (
        DELETE FROM champion_bets
        WHERE bet_id = ? AND settled = 0
        RETURNING bet_id, user_id, mise
      ), u AS (
        UPDATE users SET statcoins = statcoins + (SELECT mise FROM d)
        WHERE user_id = (SELECT user_id FROM d)
        RETURNING user_id
      ), t AS (
        INSERT INTO transactions (user_id, montant, motif)
        SELECT user_id, mise,
               '[Admin] Annulation du pari champion #' || bet_id::text
        FROM d
      )
      SELECT mise FROM d",
                   params = list(bid))

    if (nrow(res) == 1) {
      n_ok <- n_ok + 1L
      total_rendu <- total_rendu + res$mise[1]
    }
  }

  if (n_ok > 0) db_touch(con)

  list(n_annules = n_ok,
       total_rendu = total_rendu,
       n_ignores = length(bet_ids) - n_ok)
}